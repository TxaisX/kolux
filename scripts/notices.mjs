// T-783 (P3-16): THIRD-PARTY-NOTICES.txt, the licence notices that MIT, Apache-2.0, BSD and ISC code asks to travel with
// every copy. The installer carries it (tauri.conf.json bundle.resources) and Settings > About opens it.
//   node scripts/notices.mjs            regenerate src-tauri/resources/THIRD-PARTY-NOTICES.txt (run before a release)
//   node scripts/notices.mjs --check    exit 1 when the committed file differs from what the lock files give today
// Rust half: cargo-about (scripts/notices/about.toml and about.hbs), for the Windows target only. Install it in the repo, never globally:
//   download cargo-about-<version>-x86_64-pc-windows-msvc.tar.gz from https://github.com/EmbarkStudios/cargo-about/releases
//   and put cargo-about.exe in .tools/bin (the same folder as cargo-deny.exe).
// JS half: every package `pnpm licenses list --prod` names, with the licence file inside the package; equal texts are written once.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const NOTICES = path.join(ROOT, "src-tauri", "resources", "THIRD-PARTY-NOTICES.txt");
const RULE = "-".repeat(80);

export const HEADER = [
  "THIRD-PARTY NOTICES",
  "",
  "Kolux is Copyright (c) 2026 Txais Xiong. All rights reserved.",
  "",
  "Kolux includes the open-source software listed below. Each package stays under its own licence, whose text",
  "follows the list of packages that use it. This file is generated by scripts/notices.mjs from Cargo.lock and",
  "pnpm-lock.yaml; do not edit it by hand.",
  "",
].join("\n");

const normal = (t) => t.replace(/\r\n?/g, "\n").trim();

/** The licence text a package ships: its LICENSE, LICENCE or COPYING file (first match), else null. */
export function licenceText(dir) {
  if (!dir || !fs.existsSync(dir)) return null;
  const file = fs.readdirSync(dir).filter((f) => /^(licen[cs]e|copying)([.-].*)?$/i.test(f) && fs.statSync(path.join(dir, f)).isFile()).sort()[0];
  return file ? normal(fs.readFileSync(path.join(dir, file), "utf8")) : null;
}

/** `pnpm licenses list --json` entries grouped by identical licence text: [{ title, text, users: ["name version", ...] }]. */
export function groupJs(byLicense, read = licenceText) {
  const groups = new Map();
  for (const [license, pkgs] of Object.entries(byLicense)) {
    for (const p of pkgs) {
      const text = read(p.paths?.[0]);
      // A package with no licence file still owes the notice its package.json states: name the licence and the author.
      const body = text ?? `${license}\n(this package ships no licence file; the licence above is the one its package.json declares${p.author ? `, by ${p.author}` : ""})`;
      const key = `${license}\n${body}`;
      const g = groups.get(key) ?? { title: license, text: body, users: [] };
      for (const v of p.versions ?? [p.version]) g.users.push(`${p.name} ${v}${p.homepage ? ` - ${p.homepage}` : ""}`);
      groups.set(key, g);
    }
  }
  return [...groups.values()].map((g) => ({ ...g, users: [...new Set(g.users)].sort() })).sort((a, b) => a.title.localeCompare(b.title) || a.users[0].localeCompare(b.users[0]));
}

export function renderJs(groups) {
  return groups.map((g) => `${RULE}\n${g.title}\n${RULE}\nUsed by:\n${g.users.map((u) => `  ${u}`).join("\n")}\n\n${g.text}\n`).join("\n");
}

function rustHalf() {
  const exe = path.join(ROOT, ".tools", "bin", "cargo-about.exe");
  if (!fs.existsSync(exe)) throw new Error(`cargo-about is not installed at ${exe}; see the comment at the top of scripts/notices.mjs`);
  const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "kolux-notices-")), "rust.txt");
  try {
    execFileSync(exe, ["generate", "--locked", "--manifest-path", path.join(ROOT, "src-tauri", "Cargo.toml"), "-c", path.join(ROOT, "scripts", "notices", "about.toml"), path.join(ROOT, "scripts", "notices", "about.hbs"), "-o", tmp], { cwd: ROOT, stdio: ["ignore", "inherit", "inherit"], windowsHide: true });
    return normal(fs.readFileSync(tmp, "utf8"));
  } finally {
    fs.rmSync(path.dirname(tmp), { recursive: true, force: true });
  }
}

function jsHalf() {
  const json = execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { cwd: ROOT, shell: true, windowsHide: true, maxBuffer: 64 << 20, encoding: "utf8" });
  return normal(renderJs(groupJs(JSON.parse(json))));
}

export function build() {
  const rust = rustHalf();
  const js = jsHalf();
  const text = `${HEADER}\nPART 1: Rust packages (the app itself)\n\n${rust}\n\n\nPART 2: JavaScript packages (the window)\n\n${js}\n`;
  return text.replace(/[ \t]+$/gm, "");
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const text = build();
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(NOTICES) ? fs.readFileSync(NOTICES, "utf8").replace(/\r\n/g, "\n") : "";
    console.log(have === text ? "notices: OK (the committed file matches the lock files)" : "notices: STALE (run node scripts/notices.mjs and commit the result)");
    process.exit(have === text ? 0 : 1);
  }
  fs.mkdirSync(path.dirname(NOTICES), { recursive: true });
  fs.writeFileSync(NOTICES, text);
  console.log(`notices: wrote ${path.relative(ROOT, NOTICES)} (${(text.length / 1024).toFixed(0)} KB)`);
}
